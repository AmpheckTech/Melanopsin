using System.Collections.Generic;
using System.Text;

namespace Melanopsin.UI.Markup.Compiler.Styling;

internal static class CssSourceWriter {
    public static string Emit(
        string rootNamespace,
        IReadOnlyList<CssStylesheet> imports,
        string className,
        IReadOnlyList<CssTokenState> slotsInDependencyOrder,
        IReadOnlyList<CssRuleAssignment> assignments) {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        if (!string.IsNullOrWhiteSpace(rootNamespace)) {
            source.Append("namespace ").Append(rootNamespace).AppendLine(";");
            source.AppendLine();
        }

        source.Append("internal static partial class ")
            .Append(className)
            .AppendLine(" {");
        WriteTokens(source, slotsInDependencyOrder);
        WriteAddTo(source, rootNamespace, imports, assignments);
        source.AppendLine("}");
        return source.ToString();
    }

    private static void WriteTokens(
        StringBuilder source,
        IReadOnlyList<CssTokenState> slotsInDependencyOrder) {
        if (slotsInDependencyOrder.Count == 0) {
            return;
        }

        source.AppendLine("    internal static class Tokens {");
        foreach (var state in slotsInDependencyOrder) {
            source.Append("        internal static readonly ")
                .Append(CssValueSyntax.RuntimeTypeName(state.Kind))
                .Append(' ')
                .Append(state.CSharpName)
                .Append(" = ")
                .Append(state.Expression)
                .AppendLine(";");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void WriteAddTo(
        StringBuilder source,
        string rootNamespace,
        IReadOnlyList<CssStylesheet> imports,
        IReadOnlyList<CssRuleAssignment> assignments) {
        source.AppendLine("    internal static void AddTo(global::Melanopsin.UI.Styling.StyleSheet sheet) {");
        foreach (var import in imports) {
            source.Append("        ")
                .Append(CssNaming.QualifiedClassName(rootNamespace, import.Path))
                .AppendLine(".AddTo(sheet);");
        }

        foreach (var assignment in assignments) {
            source.AppendLine("        sheet.Add(new global::Melanopsin.UI.Styling.StyleRule(");
            source.Append("            ").Append(assignment.SelectorExpression).AppendLine(",");
            source.AppendLine("            new global::Melanopsin.UI.Styling.StyleProperties {");
            source.Append(assignment.Properties);
            source.AppendLine("            }));");
        }

        source.AppendLine("    }");
    }
}

using System;
using System.Collections.Generic;
using System.Text;
using Melanopsin.UI.Markup.Compiler.Resources;
using Melanopsin.UI.Markup.Compiler.Schema;
using Melanopsin.UI.Markup.Compiler.Syntax;

namespace Melanopsin.UI.Markup.Compiler.Generation;

internal static class MarkupEmitter {
    public static string Emit(
        MarkupDocument document,
        ControlCatalog controls) {
        return Emit(document, controls, ResourceManifestCatalog.Empty);
    }

    public static string Emit(
        MarkupDocument document,
        ControlCatalog controls,
        ResourceManifestCatalog resources) {
        if (document.Namespace is null ||
            document.Nodes.Count != 1 ||
            document.Nodes[0] is not MarkupElement root) {
            throw new InvalidOperationException("A validated document must contain metadata and one root element.");
        }

        var output = new StringBuilder();
        WriteTypeHeader(output, document);

        var nodes = new MarkupNodeEmitter(
            output,
            controls,
            document.ResourcePackage ?? document.Namespace,
            resources);
        var rootVariable = nodes.Emit(
            root,
            indent: 2,
            parentVariable: null,
            reconciliationKey: null);

        output.Append("        return ").Append(rootVariable).AppendLine(";");
        output.AppendLine("    }");
        WriteReferenceProperties(output, nodes.References);
        output.AppendLine("}");
        return output.ToString();
    }

    private static void WriteReferenceProperties(
        StringBuilder output,
        IReadOnlyList<MarkupReferenceBinding> references) {
        if (references.Count == 0) {
            return;
        }

        output.AppendLine();
        foreach (var reference in references) {
            output.Append("    public ")
                .Append(reference.TypeName)
                .Append(' ')
                .Append(reference.Name)
                .AppendLine(" { get; private set; } = null!;");
        }
    }

    private static void WriteTypeHeader(StringBuilder output, MarkupDocument document) {
        var className = MarkupNaming.ComponentClassName(document);
        output.AppendLine("// <auto-generated />");
        output.AppendLine("#nullable enable");
        output.Append("namespace ").Append(document.Namespace).AppendLine(";");
        output.AppendLine();
        if (document.ClassName is null) {
            output.Append("public sealed partial class ")
                .Append(className)
                .AppendLine(" : global::Melanopsin.UI.Component {");
        } else {
            output.Append("partial class ").Append(className).AppendLine(" {");
        }

        output.AppendLine();
        output.AppendLine("    protected override global::Melanopsin.UI.Node BuildCore() {");
    }
}

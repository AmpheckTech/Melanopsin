using Melanopsin.UI.Input;

namespace Melanopsin.UI.Platform.Win32;

/// <summary>
/// Maps Win32 virtual-key codes to platform-neutral input keys.
/// </summary>
public static class Win32KeyMapper {
    public static Key MapKey(int virtualKey) {
        return virtualKey switch {
            >= 0x41 and <= 0x5A => (Key)((int)Key.A + virtualKey - 0x41),
            >= 0x30 and <= 0x39 => (Key)((int)Key.D0 + virtualKey - 0x30),
            >= 0x70 and <= 0x87 => (Key)((int)Key.F1 + virtualKey - 0x70),
            >= 0x60 and <= 0x69 => (Key)((int)Key.NumPad0 + virtualKey - 0x60),
            0x08 => Key.Backspace,
            0x09 => Key.Tab,
            0x0D => Key.Enter,
            0x03 => Key.Clear,
            0x10 => Key.LeftShift,
            0x11 => Key.LeftControl,
            0x12 => Key.LeftAlt,
            0x13 => Key.Pause,
            0x14 => Key.CapsLock,
            0x15 => Key.Kana,
            0x17 => Key.Junja,
            0x18 => Key.Final,
            0x19 => Key.Hanja,
            0x1C => Key.Convert,
            0x1D => Key.NonConvert,
            0x1E => Key.Accept,
            0x1F => Key.ModeChange,
            0x1B => Key.Escape,
            0x20 => Key.Space,
            0x21 => Key.PageUp,
            0x22 => Key.PageDown,
            0x23 => Key.End,
            0x24 => Key.Home,
            0x25 => Key.Left,
            0x26 => Key.Up,
            0x27 => Key.Right,
            0x28 => Key.Down,
            0x2C => Key.PrintScreen,
            0x2A => Key.Print,
            0x29 => Key.Select,
            0x2B => Key.Execute,
            0x2F => Key.Help,
            0x2D => Key.Insert,
            0x2E => Key.Delete,
            0x5B => Key.LeftMeta,
            0x5C => Key.RightMeta,
            0x5D => Key.Apps,
            0x5F => Key.Sleep,
            0x6A => Key.NumPadMultiply,
            0x6B => Key.NumPadAdd,
            0x6C => Key.NumPadSeparator,
            0x6D => Key.NumPadSubtract,
            0x6E => Key.NumPadDecimal,
            0x6F => Key.NumPadDivide,
            0x90 => Key.NumLock,
            0x91 => Key.ScrollLock,
            0xA0 => Key.LeftShift,
            0xA1 => Key.RightShift,
            0xA2 => Key.LeftControl,
            0xA3 => Key.RightControl,
            0xA4 => Key.LeftAlt,
            0xA5 => Key.RightAlt,
            0xA6 => Key.BrowserBack,
            0xA7 => Key.BrowserForward,
            0xA8 => Key.BrowserRefresh,
            0xA9 => Key.BrowserStop,
            0xAA => Key.BrowserSearch,
            0xAB => Key.BrowserFavorites,
            0xAC => Key.BrowserHome,
            0xAD => Key.VolumeMute,
            0xAE => Key.VolumeDown,
            0xAF => Key.VolumeUp,
            0xB0 => Key.MediaNextTrack,
            0xB1 => Key.MediaPreviousTrack,
            0xB2 => Key.MediaStop,
            0xB3 => Key.MediaPlayPause,
            0xB4 => Key.LaunchMail,
            0xB5 => Key.LaunchMediaSelect,
            0xB6 => Key.LaunchApp1,
            0xB7 => Key.LaunchApp2,
            0xBA => Key.Semicolon,
            0xBB => Key.Equal,
            0xBC => Key.Comma,
            0xBD => Key.Minus,
            0xBE => Key.Period,
            0xBF => Key.Slash,
            0xC0 => Key.Backquote,
            0xE2 => Key.Oem102,
            0xDB => Key.LeftBracket,
            0xDC => Key.Backslash,
            0xDD => Key.RightBracket,
            0xDE => Key.Quote,
            _ => Key.Unknown,
        };
    }
}

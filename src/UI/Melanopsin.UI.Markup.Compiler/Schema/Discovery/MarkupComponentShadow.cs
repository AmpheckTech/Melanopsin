using System.Collections.Generic;
using System.Linq;
using System.Text;
using Melanopsin.UI.Markup.Compiler.Generation;
using Melanopsin.UI.Markup.Compiler.Syntax;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Melanopsin.UI.Markup.Compiler.Schema.Discovery;

/// <summary>
/// Mirrors a markup-only component into a throwaway syntax tree so that schema discovery,
/// completions and hover see the members that the generator emits for it.
/// </summary>
internal static class MarkupComponentShadow {
    public static SyntaxTree? Create(
        MarkupDocument document,
        Compilation compilation,
        CSharpParseOptions? parseOptions = null) {
        if (document.Namespace is not { Length: > 0 } namespaceName ||
            document.ComponentName is not { Length: > 0 } componentName ||
            compilation.GetTypeByMetadataName($"{namespaceName}.{componentName}") is not null) {
            return null;
        }

        var code = MarkupCodeEmitter.Read(document);
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated />");
        output.AppendLine("#nullable enable");
        MarkupCodeEmitter.WriteUsings(output, code, document.Path);
        output.Append("namespace ").Append(namespaceName).AppendLine(";");
        output.AppendLine();
        MarkupCodeEmitter.WriteMarker(output);
        MarkupCodeEmitter.WriteDeclaration(output, componentName);
        output.AppendLine("    protected override global::Melanopsin.UI.Node BuildCore() =>");
        output.AppendLine("        throw new global::System.NotSupportedException();");
        MarkupCodeEmitter.WriteBodies(output, code, document.Path);
        output.AppendLine("}");
        return CSharpSyntaxTree.ParseText(
            output.ToString(),
            parseOptions ?? MarkupComponentTrees.ParseOptions(compilation),
            document.Path);
    }

    public static IReadOnlyList<SyntaxTree> CreateAll(
        IReadOnlyList<MarkupDocument> documents,
        Compilation compilation) {
        if (documents.Count == 0) {
            return [];
        }

        var parseOptions = MarkupComponentTrees.ParseOptions(compilation);
        var trees = new List<SyntaxTree>();
        foreach (var document in documents) {
            if (Create(document, compilation, parseOptions) is { } tree) {
                trees.Add(tree);
            }
        }

        return trees;
    }
}

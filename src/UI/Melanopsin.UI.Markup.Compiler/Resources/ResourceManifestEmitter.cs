using System.Text;
using Melanopsin.UI.Markup.Compiler.Generation.Formatting;

namespace Melanopsin.UI.Markup.Compiler.Resources;

internal static class ResourceManifestEmitter {
    public static string Emit(ResourceManifest manifest) {
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated />");
        // Generated members carry no XML documentation; see MarkupEmitter.WriteTypeHeader.
        output.AppendLine("#pragma warning disable CS1591");
        output.AppendLine("#nullable enable");
        output.Append("namespace ").Append(manifest.Package).AppendLine(";");
        output.AppendLine();
        output.Append("public static partial class ")
            .Append(manifest.AccessorClassName)
            .AppendLine(" {");
        EmitContract(output, manifest);
        output.AppendLine();

        string? currentCategory = null;
        foreach (var definition in manifest.Definitions) {
            if (!string.Equals(currentCategory, definition.Category, StringComparison.Ordinal)) {
                if (currentCategory is not null) {
                    output.AppendLine("    }");
                    output.AppendLine();
                }

                currentCategory = definition.Category;
                output.Append("    public static class ")
                    .Append(currentCategory)
                    .AppendLine(" {");
            }

            output.Append("        public static global::Melanopsin.UI.App.ResourceKey<")
                .Append(definition.ValueTypeName)
                .Append("> ")
                .Append(definition.Name)
                .AppendLine(" { get; } =");
            output.Append("            new global::Melanopsin.UI.App.ResourceKey<")
                .Append(definition.ValueTypeName)
                .Append(">(")
                .Append(CSharpLiteral.Quote(definition.Id))
                .AppendLine(");");
        }

        if (currentCategory is not null) {
            output.AppendLine("    }");
        }

        output.AppendLine("}");
        return output.ToString();
    }

    private static void EmitContract(StringBuilder output, ResourceManifest manifest) {
        output.AppendLine(
            "    public static global::Melanopsin.UI.App.ResourceContract Contract { get; } =");
        output.AppendLine(
            "        new global::Melanopsin.UI.App.ResourceContract(");
        output.AppendLine(
            "            new global::Melanopsin.UI.App.ResourceDescriptor[] {");
        foreach (var definition in manifest.Definitions) {
            output.AppendLine(
                "                new global::Melanopsin.UI.App.ResourceDescriptor(");
            output.Append("                    ")
                .Append(CSharpLiteral.Quote(definition.Id))
                .AppendLine(",");
            output.Append("                    global::Melanopsin.UI.App.ResourceKind.")
                .Append(definition.Kind)
                .AppendLine(",");
            output.Append("                    typeof(")
                .Append(definition.ValueTypeName)
                .AppendLine("),");
            output.Append("                    ")
                .Append(ResourceVariantNames.ToCSharpExpression(definition.Variants))
                .AppendLine("),");
        }

        output.AppendLine("            },");
        output.Append("            ")
            .Append(CSharpLiteral.Quote(manifest.Package))
            .AppendLine(",");
        output.Append("            typeof(")
            .Append(manifest.AccessorClassName)
            .AppendLine(").Assembly);");
    }

    public static string HintName(ResourceManifest manifest) {
        return $"{manifest.Package}.{manifest.AccessorClassName}.Resources.g.cs";
    }
}
